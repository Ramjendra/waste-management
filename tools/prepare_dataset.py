"""
tools/prepare_dataset.py — Split labeled images into train/val and write data.yaml.

Accepts labels in two formats:
  - YOLO .txt   (from auto_label.py  — preferred)
  - labelme .json (from setup_labeling.py — converted automatically)

Run after auto_label.py or setup_labeling.py:
    python3 tools/prepare_dataset.py

Output:
    data/dataset/train/images/
    data/dataset/train/labels/
    data/dataset/val/images/
    data/dataset/val/labels/
    data/dataset/data.yaml
"""

import json
import random
import shutil
from pathlib import Path


RAW_DIR    = Path("data/raw")
LABELS_DIR = Path("data/labels")
DATASET    = Path("data/dataset")
CLASSES    = ["empty", "partial", "full"]
CLASS_ID   = {name: idx for idx, name in enumerate(CLASSES)}
IMG_EXTS   = {".jpg", ".jpeg", ".png", ".bmp"}
SPLIT      = 0.80
SEED       = 42


# ── labelme JSON → YOLO txt converter ─────────────────────────────────────────

def labelme_to_yolo(json_path: Path, img_w: int, img_h: int) -> str | None:
    """
    Convert a labelme JSON file to YOLO format string.
    Returns None if the file has no usable shapes.
    """
    try:
        data = json.loads(json_path.read_text())
    except Exception:
        return None

    lines = []
    for shape in data.get("shapes", []):
        label = shape.get("label", "").lower()
        if label not in CLASS_ID:
            continue
        pts = shape.get("points", [])
        if len(pts) < 2:
            continue

        xs = [p[0] for p in pts]
        ys = [p[1] for p in pts]
        x1, y1, x2, y2 = min(xs), min(ys), max(xs), max(ys)

        cx = ((x1 + x2) / 2) / img_w
        cy = ((y1 + y2) / 2) / img_h
        bw = (x2 - x1) / img_w
        bh = (y2 - y1) / img_h

        lines.append(f"{CLASS_ID[label]} {cx:.6f} {cy:.6f} {bw:.6f} {bh:.6f}")

    return "\n".join(lines) if lines else None


def get_image_size(img_path: Path) -> tuple[int, int]:
    try:
        import cv2
        img = cv2.imread(str(img_path))
        if img is not None:
            h, w = img.shape[:2]
            return w, h
    except Exception:
        pass
    return 640, 640   # safe fallback


# ── Label resolution (YOLO txt or labelme JSON) ────────────────────────────────

def find_label(img_path: Path) -> Path | None:
    """
    Look for a YOLO .txt first, then a labelme .json, for the given image.
    Converts JSON to .txt on the fly and saves it to LABELS_DIR.
    Returns the .txt path or None.
    """
    txt_path  = LABELS_DIR / (img_path.stem + ".txt")
    json_path = LABELS_DIR / (img_path.stem + ".json")

    if txt_path.exists():
        return txt_path

    if json_path.exists():
        w, h    = get_image_size(img_path)
        content = labelme_to_yolo(json_path, w, h)
        if content:
            txt_path.write_text(content)
            return txt_path

    return None


# ── Dataset split & copy ───────────────────────────────────────────────────────

def collect_pairs() -> list[tuple[Path, Path]]:
    pairs = []
    for img in sorted(RAW_DIR.iterdir()):
        if img.suffix.lower() not in IMG_EXTS:
            continue
        label = find_label(img)
        if label:
            pairs.append((img, label))
        else:
            print(f"[prepare] SKIP (no label): {img.name}")
    return pairs


def split_pairs(pairs: list) -> tuple[list, list]:
    random.seed(SEED)
    shuffled = pairs[:]
    random.shuffle(shuffled)
    n_train = max(1, int(len(shuffled) * SPLIT))
    return shuffled[:n_train], shuffled[n_train:]


def copy_split(pairs: list, subset: str):
    img_dir   = DATASET / subset / "images"
    label_dir = DATASET / subset / "labels"
    img_dir.mkdir(parents=True, exist_ok=True)
    label_dir.mkdir(parents=True, exist_ok=True)

    for img_path, label_path in pairs:
        shutil.copy(img_path,   img_dir   / img_path.name)
        shutil.copy(label_path, label_dir / (label_path.stem + ".txt"))

    print(f"[prepare]   {subset:5s}  →  {len(pairs)} images")


def write_yaml() -> Path:
    yaml_path = DATASET / "data.yaml"
    names_str = "\n".join(f"  {i}: {n}" for i, n in enumerate(CLASSES))
    # Use resolve() so the path is always correct for the current machine
    yaml_path.write_text(f"""# Auto-generated by tools/prepare_dataset.py
path: {DATASET.resolve()}
train: train/images
val:   val/images

nc: {len(CLASSES)}
names:
{names_str}
""")
    print(f"[prepare] data.yaml → {yaml_path.resolve()}")
    return yaml_path


# ── Main ───────────────────────────────────────────────────────────────────────

def main():
    pairs = collect_pairs()

    if not pairs:
        print(f"\n[ERROR] No labeled images found.")
        print(f"  Images  → {RAW_DIR.resolve()}")
        print(f"  Labels  → {LABELS_DIR.resolve()} (.txt or .json)")
        print(f"\n  Run one of:")
        print(f"    python3 tools/auto_label.py        (automatic, recommended)")
        print(f"    python3 tools/setup_labeling.py    (manual GUI)")
        return

    print(f"\n[prepare] {len(pairs)} labeled image(s) found.")

    if len(pairs) < 10:
        print("[WARNING] Fewer than 10 images — accuracy will be limited.")
        print("          Run  python3 tools/download_images.py --per-class 60  for more.")

    train_pairs, val_pairs = split_pairs(pairs)
    if not val_pairs:
        val_pairs = train_pairs  # too few images: reuse train as val

    if DATASET.exists():
        shutil.rmtree(DATASET)

    copy_split(train_pairs, "train")
    copy_split(val_pairs,   "val")
    write_yaml()

    print(f"\n[prepare] Dataset ready.")
    print(f"          Next step:  python3 tools/train.py\n")


if __name__ == "__main__":
    main()
